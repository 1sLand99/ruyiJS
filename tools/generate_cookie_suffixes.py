"""Generate the CookieStore's immutable PSL from the selected Firefox source."""
from hashlib import sha256
import json
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
source=Path(sys.argv[1]) if len(sys.argv)>1 else Path('D:/firefox/src/firefox/netwerk/dns/effective_tld_names.dat')
rules=[]
for line in source.read_text('utf-8').splitlines():
    line=line.strip()
    if line and not line.startswith('//'):
        rules.append('.'.join(label.encode('idna').decode('ascii') for label in line.split('.')))
out=ROOT/'src/domain/resource_network/cookie_suffix_data.h'
out.write_text('// Mozilla Public License 2.0: https://mozilla.org/MPL/2.0/\n'
    '// Generated by tools/generate_cookie_suffixes.py; do not edit.\n#pragma once\n'
    '#include <string_view>\nnamespace ruyijs::domain::resource_network {\n'
    'inline constexpr std::string_view kCookieSuffixRules[] = {\n'+
    ''.join('  '+json.dumps(x)+',\n' for x in sorted(set(rules)))+'};\n}\n','utf-8')
(ROOT/'docs/cookie_suffix_source.json').write_text(json.dumps(dict(source=str(source),
    sha256=sha256(source.read_bytes()).hexdigest(),entries=len(set(rules)),
    generatedSHA256=sha256(out.read_bytes()).hexdigest()),indent=2),'utf-8')
