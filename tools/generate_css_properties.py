"""Generate the CSSStyleProperties named-accessor table for document_model.

Inputs: the donor's generated CSSStyleProperties.webidl (accessor name and
BindingAlias names -> canonical property id and declaring attribute, which
Firefox's setter errors name) and the recorded Firefox generation input
of the names Firefox 158 exposes on CSSStyleProperties.prototype, in order.
Exposure is decided by runtime Func checks, so the fixture is authoritative for
which names exist; the webidl is authoritative for which property each names.
"""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEBIDL = Path('D:/firefox/src/firefox/obj-jscall-check/dom/bindings/CSSStyleProperties.webidl')
PROFILE = ROOT/'profiles/generation/css_style_properties_firefox.json'
DEST = ROOT/'src/document_model'
HEADER = '// Generated by tools/generate_css_properties.py.\n'


def webidl_names(text):
    """name -> (canonical property, the webidl attribute that declares it)."""
    names = {}
    for line in text.splitlines():
        match = re.search(r'NonCustomCSSPropertyId, eCSSProperty_(\w+)\)', line)
        if not match:
            continue
        prop = match.group(1).replace('_', '-')
        attribute = re.search(r'UTF8String (\w+);', line).group(1)
        for name in [attribute] + re.findall(r'BindingAlias="([^"]+)"', line):
            assert names.setdefault(name, (prop, attribute)) == (prop, attribute), name
    return names


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--webidl', type=Path, default=WEBIDL,
                        help='Matching donor CSSStyleProperties.webidl')
    parser.add_argument('--profile', type=Path, default=PROFILE,
                        help='Recorded CSS property exposure generation input')
    args = parser.parse_args()
    names = webidl_names(args.webidl.read_text('utf-8'))
    exposed = json.loads(args.profile.read_text('utf-8'))['value']['names']
    missing = [n for n in exposed if n not in names]
    assert not missing, missing
    order = [n for n in names if n in set(exposed)]
    assert order == exposed, 'Firefox exposure order differs from the webidl order'
    rows = ['{"%s", "%s", "%s"},' % (n, names[n][0], names[n][1]) for n in exposed]
    lines, line = [], ''
    for row in rows:
        if len(line) + len(row) > 98:
            lines.append(line.rstrip()); line = ''
        line += row + ' '
    lines.append(line.rstrip())
    for old in DEST.glob('css_properties*.inc'):
        old.unlink()
    includes = []
    for i in range(0, len(lines), 160):
        name = f'css_properties_{i // 160}.inc'
        (DEST/name).write_text(HEADER + '\n'.join(lines[i:i + 160]) + '\n', encoding='utf-8')
        includes.append('#include "document_model/%s"' % name)
    (DEST/'css_properties.inc').write_text(HEADER + '\n'.join(includes) + '\n', encoding='utf-8')
    print(len(exposed), 'accessors,', len(set(names[n][0] for n in exposed)), 'properties')


if __name__ == '__main__':
    main()
