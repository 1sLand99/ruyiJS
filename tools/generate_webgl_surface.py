"""Generate native declarations from captured Firefox 157 WebIDL metadata.

Inputs are recorded, read-only descriptor generation data. Behaviour lives in the
WebGL owner, not in this generator or a JavaScript bootstrap overlay.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT/'src/web_graphics'
PROFILES = ROOT/'profiles/generation'


def chunks(stem, lines):
    files = []
    for i in range(0, len(lines), 160):
        name = f'{stem}_{i//160}.inc'
        (DEST/name).write_text('// Generated by tools/generate_webgl_surface.py.\n' +
            '\n'.join(lines[i:i+160])+'\n', encoding='utf-8')
        files.append(name)
    return '\n'.join('#include "web_graphics/'+name+'"' for name in files)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--profiles', type=Path, default=PROFILES,
                        help='Directory containing recorded WebGL generation inputs')
    args = parser.parse_args()
    firefox = json.loads((args.profiles/'webgl_firefox_surface.json').read_text('utf-8'))
    surface = firefox['contexts']
    existing = set(json.loads((args.profiles/'webgl_public_surface.json').read_text('utf-8'))['existingMethods'])
    ops = {'getContextAttributes':'kAttributes','checkFramebufferStatus':'kFramebufferComplete',
        'clientWaitSync':'kWaitComplete','getAttribLocation':'kZero','getVertexAttribOffset':'kZero',
        'getFragDataLocation':'kMinusOne','getUniformBlockIndex':'kInvalidIndex',
        'isContextLost':'kFalse','isEnabled':'kFalse','getAttachedShaders':'kEmptyArray',
        'getUniformIndices':'kEmptyArray','getBufferSubData':'kVoid'}
    state_ops = {
        'enable':'kEnable', 'disable':'kDisable', 'isEnabled':'kIsEnabled',
        'blendEquation':'kBlendEquation', 'blendEquationSeparate':'kBlendEquationSeparate',
        'blendFunc':'kBlendFunc', 'blendFuncSeparate':'kBlendFuncSeparate',
        'blendColor':'kBlendColor', 'cullFace':'kCullFace', 'frontFace':'kFrontFace',
        'lineWidth':'kLineWidth', 'depthFunc':'kDepthFunc', 'depthMask':'kDepthMask',
        'depthRange':'kDepthRange', 'clearDepth':'kClearDepth', 'clearColor':'kClearColor',
        'clearStencil':'kClearStencil', 'colorMask':'kColorMask', 'stencilFunc':'kStencilFunc',
        'stencilFuncSeparate':'kStencilFuncSeparate', 'stencilMask':'kStencilMask',
        'stencilMaskSeparate':'kStencilMaskSeparate', 'stencilOp':'kStencilOp',
        'stencilOpSeparate':'kStencilOpSeparate', 'polygonOffset':'kPolygonOffset',
        'scissor':'kScissor', 'viewport':'kViewport', 'pixelStorei':'kPixelStorei',
        'hint':'kHint', 'sampleCoverage':'kSampleCoverage'}
    for name in ['getShaderSource','getShaderInfoLog','getProgramInfoLog','getActiveUniformBlockName']:
        ops[name] = 'kEmptyString'
    # The calls whose real shader, program, buffer, attribute, uniform, draw and
    # readback state is handled by the draw path (DrawCall in draw_calls.cpp).
    draw_ops = {'shaderSource':'kShaderSource', 'compileShader':'kCompileShader',
        'attachShader':'kAttachShader', 'linkProgram':'kLinkProgram',
        'useProgram':'kUseProgram', 'bufferData':'kBufferData',
        'getAttribLocation':'kGetAttribLocation',
        'enableVertexAttribArray':'kEnableVertexAttrib',
        'disableVertexAttribArray':'kDisableVertexAttrib',
        'vertexAttribPointer':'kVertexAttribPointer',
        'uniform1f':'kUniformFloat', 'uniform2f':'kUniformFloat',
        'uniform3f':'kUniformFloat', 'uniform4f':'kUniformFloat',
        'drawArrays':'kDrawArrays', 'readPixels':'kReadPixels',
        'getProgramParameter':'kGetProgramParameter',
        'getShaderParameter':'kGetShaderParameter',
        'getShaderSource':'kGetShaderSource', 'getAttachedShaders':'kGetAttachedShaders'}
    objects = {'Query':7,'Sampler':8,'Sync':9,'TransformFeedback':10,'VertexArray':11}
    constants, methods = [], []
    for version, name in [(1,'WebGLRenderingContext'),(2,'WebGL2RenderingContext')]:
        for key, value in surface[name]['constants'].items():
            constants.append('{%d, "%s", %.0f},' % (version,key,value))
        for key, length in surface[name]['methods'].items():
            if key not in existing:
                native, slot = 'PublicCall', state_ops.get(key, ops.get(key, 'kNull' if key.startswith('get') else 'kVoid'))
                if key in state_ops: native = 'StateCall'
                if key == 'getShaderPrecisionFormat': native,slot = 'GetShaderPrecision','0'
                for suffix, kind in objects.items():
                    for action, offset in [('create',0),('delete',1),('is',2)]:
                        if key == action+suffix: native,slot = 'ExtraObjectCall',str(kind*3+offset)
                if key == 'fenceSync': native,slot = 'ExtraObjectCall','27'
                if key in draw_ops: native,slot = 'DrawCall', draw_ops[key]
                methods.append('{%d, "%s", %s, %d, %s},' % (version,key,native,length,slot))
    inc_c = chunks('public_constants', constants)
    inc_m = chunks('public_methods', methods)
    code = '''#include "web_graphics/internal.h"
#include "web_graphics/public_calls.h"
namespace ruyijs::web_graphics {
namespace {
struct Constant { int version; const char* name; double value; };
const Constant kConstants[] = {
%s
};
struct ConstructorConstant { int version; const char* name; double value; };
const ConstructorConstant kConstructorConstants[] = {
%s
};
struct Method { int version; const char* name; JSNative native; unsigned length; int op; };
const Method kMethods[] = {
%s
};
}
bool InstallPublicSurface(State& s) {
  for (const auto& c : kConstants) {
    WebFace& f = c.version == 1 ? s.context : s.context2;
    JS::RootedValue v(s.cx, JS::NumberValue(c.value));
    const unsigned flags = JSPROP_ENUMERATE | JSPROP_READONLY | JSPROP_PERMANENT;
    if (!JS_DefineProperty(s.cx, f.prototype, c.name, v, flags) ||
        !JS_DefineProperty(s.cx, f.constructor, c.name, v, flags)) return false;
  }
  for (const auto& c : kConstructorConstants) {
    WebFace& f = c.version == 1 ? s.context : s.context2;
    JS::RootedValue v(s.cx, JS::NumberValue(c.value));
    const unsigned flags = JSPROP_ENUMERATE | JSPROP_READONLY | JSPROP_PERMANENT;
    if (!JS_DefineProperty(s.cx, f.constructor, c.name, v, flags)) return false;
  }
  for (const auto& m : kMethods) {
    WebFace& f = m.version == 1 ? s.context : s.context2;
    if (!s.kit.Method(f, m.version == 1 ? "WebGLRenderingContext" : "WebGL2RenderingContext",
                      m.name, m.native, m.length, m.op | (m.version << 16))) return false;
  }
  const char* attrs[] = {"canvas","drawingBufferWidth","drawingBufferHeight","drawingBufferColorSpace","unpackColorSpace"};
  for (int version = 1; version <= 2; ++version) {
    WebFace& f = version == 1 ? s.context : s.context2;
    for (int i = 0; i < 5; ++i)
      if (!s.kit.Accessor(f, version == 1 ? "WebGLRenderingContext" : "WebGL2RenderingContext",
          attrs[i], ContextAttribute, i >= 3 ? SetContextColorSpace : nullptr, i | (version << 16))) return false;
  }
  return true;
}
}
''' % (inc_c, '\n'.join('{%d, "%s", %.0f},' % (version, key, value)
                         for version, name in [(1,'WebGLRenderingContext'),
                                               (2,'WebGL2RenderingContext')]
                         for key, value in surface[name].get('constructorConstants', {}).items()), inc_m)
    (DEST/'surface_install.cpp').write_text(code, encoding='utf-8')
    extensions = firefox['extensions']
    ext_defs, ext_constants, ext_methods = [], [], []
    operations = {'createQueryEXT':1,'createVertexArrayOES':2,'isQueryEXT':3,
        'isVertexArrayOES':4,'deleteQueryEXT':5,'deleteVertexArrayOES':6,
        'getTranslatedShaderSource':7,'getSupportedProfiles':8,
        'getQueryEXT':9,'getQueryObjectEXT':9}
    for name, value in extensions.items():
        index = len(ext_defs)
        ext_defs.append('{"%s", "%s"},' % (name, name))
        for key, number in value['constants'].items():
            ext_constants.append('{%d, "%s", %.0f},' % (index,key,number))
        for key, length in value['methods'].items():
            ext_methods.append('{%d, "%s", %d, %d},' %
                (index,key,length,index*64+operations.get(key,0)))
    chunks('extension_defs',ext_defs)
    chunks('extension_constants',ext_constants)
    chunks('extension_methods',ext_methods)


if __name__ == '__main__':
    main()
